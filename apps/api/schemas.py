import re
from typing import Literal
from pydantic import BaseModel, ConfigDict, Field, model_validator

class Observation(BaseModel):
    model_config = ConfigDict(extra='forbid')
    timestamp_start: float = Field(ge=0)
    timestamp_end: float = Field(ge=0)
    actors: list[str] = Field(max_length=20)
    observation: str = Field(min_length=3, max_length=1000)

    @model_validator(mode='after')
    def validate_observation(self):
        if self.timestamp_end < self.timestamp_start:
            raise ValueError('Observation end precedes start')
        if re.search(r'\b(criminal|guilty|robbery|burglary|theft|assault|murder|rape|kidnapping|ethnicity|race|suspect|male|female|man|woman|men|women|boy|girl|disabled)\b', self.observation, re.I):
            raise ValueError('Observation contains unsupported legal or personal inference')
        if any(not re.fullmatch(r'person_[a-z0-9]+', a) for a in self.actors):
            raise ValueError('Actors must be anonymous person labels')
        return self

class Detection(BaseModel):
    model_config = ConfigDict(extra='forbid')
    state: Literal['NORMAL','WATCH','REVIEW_REQUIRED','HIGH_PRIORITY_REVIEW']
    confidence: float = Field(ge=0, le=1)
    observable_events: list[Observation] = Field(max_length=20)
    uncertainties: list[str] = Field(max_length=20)
    supporting_frames: list[int] = Field(max_length=100)
    simulated: bool = False
    # Set by the detector cascade (ml/cascade.py); never generated by a model.
    incident_type: Literal['person_down','altercation','rack_activity'] | None = None
    rule_evidence: list[str] = Field(default_factory=list, max_length=10)
    action: Literal['physical_contact','object_taking','ordinary_activity','insufficient_visibility'] | None = None

    @model_validator(mode='after')
    def consistent_action(self):
        if self.action and self.state=='NORMAL' and self.action!='ordinary_activity':
            raise ValueError('NORMAL must describe ordinary activity')
        if self.action=='ordinary_activity' and self.state!='NORMAL':
            raise ValueError('Ordinary activity must not assert a positive review state')
        return self

class Review(BaseModel):
    decision: Literal['confirmed','dismissed','needs_review']
    note: str = Field(default='', max_length=2000)

class SourceRequest(BaseModel):
    name: str = Field(default='Phone camera', min_length=1, max_length=80)
    kind: Literal['phone','webcam','rtsp'] = 'phone'
    url: str | None = None

class Envelope(BaseModel):
    status: Literal['ok','unavailable','failed']
    model: str
    revision: str
    device: str = 'cpu'
    latency_ms: float = 0
    peak_vram_mb: float | None = None
    outputs: dict = Field(default_factory=dict)
    warnings: list[str] = Field(default_factory=list)
    error: str | None = None
